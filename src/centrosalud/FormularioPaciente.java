    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            // Obtener los datos del formulario
            String dni = txtDni.getText();
            String nombres = txtNombres.getText();
            String apellidos = txtApellidos.getText();
            String direccion = txtDireccion.getText();

            // Convertir la edad a entero
            int edad = Integer.parseInt(txtEdad.getText().trim());

            // Registrar paciente mediante el controlador
            Paciente paciente = pacienteController.registrarPaciente(
                dni, nombres, apellidos, edad, direccion
            );

            // Mostrar codigo generado
            txtCodigo.setText(paciente.getCodigo());

            // Actualizar tabla
            actualizarTabla();

            // Mostrar confirmacion
            JOptionPane.showMessageDialog(
                this,
                "Paciente registrado correctamente.\nCódigo: " + paciente.getCodigo(),
                "Registro exitoso",
                JOptionPane.INFORMATION_MESSAGE
            );
        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                this,
                "La edad debe ser un número entero.",
                "Error de datos",
                JOptionPane.ERROR_MESSAGE
            );

        txtEdad.requestFocus();

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Error de validación",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }
